/* The ADSP Q6 PLL already runs, so the core is released with the FSM */
static TEE_Result lpass_fw_start(struct qcom_pas_data *data)
{
	vaddr_t base = io_pa_or_va(&data->base, data->size);
	vaddr_t q6ss = q6ss_base(data);

	if (!base || !q6ss)
		return TEE_ERROR_GENERIC;

	/* Boot from RST_EVB, not from the fused EVB */
	io_write32(q6ss + QDSP6SS_RST_EVB, QDSP6SS_EVB_ADDR(data->fw_base));
	io_clrbits32(base + LPASS_EFUSE_Q6SS_EVB_SEL, EVB_SEL_FUSED);
	io_clrbits32(base + LPASS_ALT_RESET_Q6SS, Q6SS_ALT_RESET_ARES);

	return q6ss_boot(q6ss, true);
}

const struct qcom_pas_ops lpass_ops = {
	.fw_start = lpass_fw_start,
	.fw_shutdown = q6ss_shutdown,
	.devmem = lpass_mem_res,
	.devmem_num = ARRAY_SIZE(lpass_mem_res),
};
