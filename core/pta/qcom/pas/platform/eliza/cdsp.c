/* The NSP Q6 PLL, core clock and core start follow, in the clock driver */
static TEE_Result cdsp_fw_start(struct qcom_pas_data *data)
{
	vaddr_t q6ss = q6ss_base(data);

	if (!q6ss)
		return TEE_ERROR_GENERIC;

	io_write32(q6ss + QDSP6SS_RST_EVB, QDSP6SS_EVB_ADDR(data->fw_base));

	return q6ss_boot(q6ss, false);
}

const struct qcom_pas_ops cdsp_ops = {
	.fw_start = cdsp_fw_start,
	.fw_shutdown = q6ss_shutdown,
	.devmem = turing_mem_res,
	.devmem_num = ARRAY_SIZE(turing_mem_res),
};
